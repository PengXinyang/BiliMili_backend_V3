CREATE TABLE IF NOT EXISTS chat (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 post_id INT NOT NULL,
 accept_id INT NOT NULL,
 is_deleted INT NOT NULL DEFAULT 0,
 unread_num INT NOT NULL DEFAULT 0,
 latest_time TIMESTAMP(3) NOT NULL,
 UNIQUE (post_id, accept_id)
);
CREATE TABLE IF NOT EXISTS chat_detailed (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 post_id INT NOT NULL,
 accept_id INT NOT NULL,
 content VARCHAR(500) NOT NULL,
 post_del INT NOT NULL DEFAULT 0,
 accept_del INT NOT NULL DEFAULT 0,
 withdraw INT NOT NULL DEFAULT 0,
 time TIMESTAMP(3) NOT NULL,
 status INT NOT NULL DEFAULT 1,
 read_flag INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS message_unread (
 uid INT PRIMARY KEY,
 reply INT NOT NULL DEFAULT 0,
 at_num INT NOT NULL DEFAULT 0,
 up_vote INT NOT NULL DEFAULT 0,
 system_message INT NOT NULL DEFAULT 0,
 message INT NOT NULL DEFAULT 0,
 `dynamic` INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS message_event (
 event_id VARCHAR(128) PRIMARY KEY,
 uid INT NOT NULL,
 kind VARCHAR(32) NOT NULL,
 created_at TIMESTAMP(3) NOT NULL
);
